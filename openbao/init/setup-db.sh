#!/bin/sh
set -e

export BAO_ADDR="${BAO_ADDR:-http://openbao:8200}"
export BAO_TOKEN="${BAO_TOKEN:-dev-root-token}"

# Postgres superuser password. openbao-init writes it into this container's
# volume (certs_openbao) and, identically, into postgres's (certs_postgres),
# where postgres reads it via POSTGRES_PASSWORD_FILE.
PG_ROOT_PASSWORD_FILE="${PG_ROOT_PASSWORD_FILE:-/openbao/certs/pg_root_password}"
if [ ! -s "${PG_ROOT_PASSWORD_FILE}" ]; then
    echo "ERROR: ${PG_ROOT_PASSWORD_FILE} missing or empty." >&2
    echo "This file is generated by openbao-init; ensure it ran successfully." >&2
    exit 1
fi
DB_ROOT_PASSWORD="$(cat "${PG_ROOT_PASSWORD_FILE}")"

echo "=== OpenBao DB init: waiting for OpenBao ==="
until bao status >/dev/null 2>&1; do sleep 1; done

# ── Bootstrap app_owner group role ────────────────────────────────────
# Every ephemeral app role OpenBao mints needs to own (or act as owner of)
# all schema objects, so DDL operations like CREATE INDEX and ALTER TABLE
# keep working across role rotations. We solve this with a single
# non-login role "app_owner" that owns every object, and arrange for
# each dynamic role to SET ROLE = app_owner on connect. That way Liquibase
# migrations run as app_owner regardless of which ephemeral role is
# currently active, and stale tables owned by a previous dynamic role
# don't prevent future DDL.
echo "=== Bootstrapping app_owner role ==="
# Postgres only accepts TCP logins over mTLS (postgres/pg_hba_mtls.conf). The
# superuser's cert CN must be `kernfolio`. libpq accepts the key: it's owned
# by this process's uid with mode 0600.
export PGSSLMODE=verify-full
export PGSSLROOTCERT=/openbao/certs/ca.pem
export PGSSLCERT=/openbao/certs/postgres-admin-client.pem
export PGSSLKEY=/openbao/certs/postgres-admin-client-key.pem
# SCRAM channel binding (tls-server-end-point) hashes the server cert with its
# signature digest, and Ed25519 has none: libpq fails with "could not find
# digest for NID UNDEF". verify-full + the client cert already rule out a MITM.
export PGCHANNELBINDING=disable
export PGPASSWORD="${DB_ROOT_PASSWORD}"
psql -h postgres -U kernfolio -d kernfolio -v ON_ERROR_STOP=1 <<'SQL'
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_owner') THEN
        CREATE ROLE app_owner NOLOGIN;
    END IF;
END
$$;
GRANT ALL ON SCHEMA public TO app_owner;
ALTER SCHEMA public OWNER TO app_owner;
SQL
unset PGPASSWORD PGSSLMODE PGSSLROOTCERT PGSSLCERT PGSSLKEY PGCHANNELBINDING

# ── Database secrets engine ──────────────────────────────────────────
echo "=== Enabling database secrets engine ==="
bao secrets enable database 2>/dev/null || true

# The OpenBao server opens this connection itself, so the cert paths are in
# the openbao container (it mounts certs_openbao read-only). channel_binding:
# see PGCHANNELBINDING above; pgx would otherwise attempt SCRAM-SHA-256-PLUS.
# username_template pins the `v-token-app-` prefix that pg_hba_mtls.conf
# matches on; the default template would change it with the auth method.
bao write database/config/kernfolio \
  plugin_name=postgresql-database-plugin \
  allowed_roles="app" \
  connection_url="postgresql://{{username}}:{{password}}@postgres:5432/kernfolio?sslmode=verify-full&sslrootcert=/openbao/certs/ca.pem&sslcert=/openbao/certs/postgres-admin-client.pem&sslkey=/openbao/certs/postgres-admin-client-key.pem&channel_binding=disable" \
  username_template='{{ printf "v-token-app-%s-%s" (random 20) (unix_time) | truncate 63 }}' \
  username="kernfolio" \
  password="${DB_ROOT_PASSWORD}"

# creation_statements:
#   - Create the ephemeral login role with an expiration.
#   - Make it a member of app_owner so it inherits the group's privileges.
#   - Pin role=app_owner at the role level so every session the dynamic role
#     opens automatically runs as app_owner. Tables, indexes, and Liquibase
#     metadata created in that session are owned by app_owner — not by the
#     ephemeral role — so subsequent role rotations can keep editing schema.
bao write database/roles/app \
  db_name=kernfolio \
  creation_statements="CREATE ROLE \"{{name}}\" WITH LOGIN PASSWORD '{{password}}' VALID UNTIL '{{expiration}}' IN ROLE app_owner INHERIT; \
    ALTER ROLE \"{{name}}\" SET ROLE = app_owner;" \
  revocation_statements="DROP ROLE IF EXISTS \"{{name}}\";" \
  default_ttl="1h" \
  max_ttl="24h"

echo "=== OpenBao DB init complete ==="
